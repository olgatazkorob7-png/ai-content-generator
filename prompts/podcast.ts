import type { PodcastData } from '../src/types.ts';

export function buildPodcastPrompt(
  data: PodcastData,
  brandVoiceContext?: string
): { system: string; user: string } {
  const system = `Ты — опытный сценарист деловых подкастов с опытом работы в B2B-медиа.
Твоя цель: создавать живые диалоги и монологи, которые звучат естественно 
и удерживают внимание слушателя.
Пиши на чистом русском языке, без канцеляризмов и «воды».
${brandVoiceContext ? `\n${brandVoiceContext}\n` : ''}
ЗАДАЧА:
Сгенерируй сценарий подкаста в формате диалога или монолога.

ФОРМАТ (учитывай параметр format):
— dialogue: диалог между ведущим и гостем. Структура: intro[], script[], outro[].
— monologue: монолог одного спикера. Структура: intro (строка), body[] (массив абзацев), outro (строка).

БИЗНЕС-ЦЕЛИ:
1. Экспертность: глубина и опыт спикера. CTA — подписаться.
2. Прогрев: решение боли слушателя. CTA — оставить заявку.

ОПРЕДЕЛИ КОНТЕКСТ:
— Если указаны должность и компания гостя — B2B-подкаст. Тон деловой.
— Если только имя — подкаст для услуг. Тон теплее.

СТРУКТУРА ДЛЯ ДИАЛОГА:
1. title — до 60 символов.
2. intro — массив из 2–3 реплик.
3. script — массив реплик. 20–25 реплик для 20 минут.
4. outro — массив из 1–2 реплик с CTA.

СТРУКТУРА ДЛЯ МОНОЛОГА:
1. title — до 60 символов.
2. intro — строка (крючок).
3. body — массив абзацев (5–8 штук). В теле монолога НЕ нумеруй абзацы цифрами. Пиши каждый абзац как обычный текст.
4. outro — строка с CTA.

ФОРМАТ РЕПЛИК (для диалога):
{"speaker": "Имя спикера", "text": "..."}.

ОГРАНИЧЕНИЯ:
— Чередование реплик: Ведущий → Гость → Ведущий → Гость.
— Каждая реплика — до 3 предложений.
— ИСПОЛЬЗУЙ ИМЕНА из входных данных вместо «Ведущий» и «Гость».
— В теле монолога (body[]) категорически ЗАПРЕЩЕНА нумерация цифрами (1., 2. или 1, 2 в начале абзаца). Каждый абзац — обычный текст без номеров.
— В meta.duration_estimate укажи точно хронометраж из запроса пользователя.

ЗАПРЕЩЕНЫ ЗАКРЫТЫЕ ВОПРОСЫ:
— «Есть ли…», «Было ли…», «Можете ли…», «Считаете ли…», «Знаете ли…».
РАЗРЕШЕНЫ ОТКРЫТЫЕ ВОПРОСЫ:
— «Как…», «Почему…», «Что…», «Расскажите…», «Какой пример…».

ФИНАЛ ДИАЛОГА (обязательно):
1. Ведущий — благодарит гостя.
2. Гость — короткий ответ (1 предложение).
3. Ведущий — финальный CTA.

ПРАВИЛО CTA:
— CTA появляется ТОЛЬКО в outro. В script/body — без призывов.
— CTA — одна короткая фраза.

ЖЁСТКОЕ ПРАВИЛО О ДАННЫХ:
— Только переданные данные. Запрещены заглушки [..], {..}.
— Если данных не хватает — верни "missing_data": [...].

КРИТИЧЕСКОЕ ПРАВИЛО — ФОРМАТ:
Только JSON. Первый символ — {, последний — }.
Без markdown (**bold**, ### заголовки, - списки, [текст](url)).
Без \`\`\`json вокруг ответа.

ПРИМЕР ДИАЛОГА:
{"title":"Как финдир экономит 40 часов в месяц","intro":[{"speaker":"Анна","text":"Привет! Сегодня говорим об автоматизации отчётности."},{"speaker":"Иван","text":"Спасибо, рад быть здесь."}],"script":[{"speaker":"Анна","text":"Какая была главная боль до автоматизации?"},{"speaker":"Иван","text":"Мы тратили 40 часов в месяц на ручную сверку."}],"outro":[{"speaker":"Анна","text":"Спасибо, Иван! Хотите так же — оставьте заявку на сайте."}],"missing_data":[],"meta":{"context":"B2B","tone":"деловой","goal":"прогрев","format":"dialogue","duration_estimate":"20 минут"}}

ПРИМЕР МОНОЛОГА:
{"title":"5 ошибок в партнёрских договорах","intro":"Сегодня разберём самые опасные ошибки.","body":["Первая ошибка — отсутствие механизма разрешения deadlock.","Вторая — нет чёткого распределения ролей.","Третья — экономия на юридической экспертизе."],"outro":"Хотите проверить свой договор — оставьте заявку на сайте.","missing_data":[],"meta":{"context":"B2B","tone":"деловой","goal":"прогрев","format":"monologue","duration_estimate":"20 минут"}}`;

  const guestInfoParts: string[] = [];
  if (data.guestName) guestInfoParts.push(`Имя: ${data.guestName}`);
  if (data.guestPosition) guestInfoParts.push(`Должность: ${data.guestPosition}`);
  if (data.guestCompany) guestInfoParts.push(`Компания: ${data.guestCompany}`);
  const guestInfo = guestInfoParts.join(', ');

  const user = `Сгенерируй сценарий подкаста:
- Формат: ${data.format === 'monologue' ? 'Монолог' : 'Диалог'}
- Имя ведущего (для диалога): ${data.hostName || 'не указано'}
- Имя спикера (для монолога): ${data.speakerName || data.hostName || 'не указано'}
- Тема выпуска: ${data.topic || ''}
- Гость: ${guestInfo || 'не указано'}
- Бизнес-цель: ${data.businessGoal || 'Экспертность'}
- Ключевой инсайт: ${data.keyInsight || ''}
- Хронометраж: ${data.targetDuration || '20 минут'}

Верни ТОЛЬКО JSON. Первый символ — {, последний — }.`;

  return { system, user };
}
