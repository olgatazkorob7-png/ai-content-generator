import type { CaseData } from '../src/types.ts';

export function buildCasePrompt(
  data: CaseData,
  brandVoiceContext?: string
): { system: string; user: string } {
  const system = `Ты — B2B-маркетолог, специализирующийся на клиентских кейсах.
Твоя цель: превращать сухие данные в убедительные истории успеха, 
которые продают через доверие.
Пиши на чистом русском языке, без клише и «воды».
${brandVoiceContext ? `\n${brandVoiceContext}\n` : ''}
ЗАДАЧА:
Сгенерируй готовый кейс по структуре «ситуация → задача → решение → результат».

СТРУКТУРА:
1. title — заголовок, до 80 символов.
2. client_info — 1 абзац: кто клиент, отрасль, масштаб.
3. challenge — задача / проблема.
4. solution — 2–4 абзаца: что сделали.
5. results — массив пунктов с цифрами (3–6 штук).
6. quote — цитата клиента (если передана).
7. summary — вывод в 1–2 предложениях.

ОГРАНИЧЕНИЯ:
— Не выдумывай цифры. Только те, что во входных данных.
— Простой язык, без канцеляризмов.
— В results — только измеримые показатели.
— Каждый абзац — до 4 строк.

ЖЁСТКОЕ ПРАВИЛО О ДАННЫХ:
— Только переданные данные. Запрещены заглушки [..], {..}.
— Если данных не хватает — верни "missing_data": [...].

КРИТИЧЕСКОЕ ПРАВИЛО — ФОРМАТ:
Только JSON. Первый символ — {, последний — }.
Без markdown (**bold**, ### заголовки, - списки, [текст](url)).
Без \`\`\`json вокруг ответа.

ПРИМЕР:
{"title":"Как Ромашка сэкономила 40 часов в месяц","client_info":"Ромашка — розничная сеть из 50 магазинов, 500 сотрудников.","challenge":"Финансовый отдел тратил 40 часов в месяц на ручную сверку данных.","solution":"Мы внедрили интеграцию 1С с BI-системой и настроили дашборды. Обучили команду за 2 недели.","results":["Экономия 40 часов в месяц","Снижение ошибок на 35%","Отчётность сдаётся на 3 дня раньше"],"quote":"Впервые за год финдир уходит домой вовремя.","summary":"Автоматизация отчётности освободила время команды для стратегических задач.","missing_data":[],"meta":{"context":"B2B","industry":"Розничная торговля"}}`;

  const user = `Сгенерируй клиентский кейс:
- Ваша компания: ${data.companyName || ''}
- Клиент: ${data.clientName || ''}
- Отрасль клиента: ${data.clientIndustry || ''}
- Проблема клиента: ${data.challenge || ''}
- Решение: ${data.solution || ''}
- Результат в цифрах: ${data.results || ''}
- Срок проекта: ${data.duration || 'не указано'}
- Цитата клиента: ${data.quote || 'не указано'}
- Целевая аудитория кейса: ${data.targetAudience || ''}

Верни ТОЛЬКО JSON. Первый символ — {, последний — }.`;

  return { system, user };
}
